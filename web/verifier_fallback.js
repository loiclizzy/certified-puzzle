  for (let r=2;r<6;r++) for (let c=0;c<7;c++) board.add(`${r},${c}`);
  for (let c=0;c<3;c++) board.add(`6,${c}`);

  const monthCell = m => m <= 6 ? [0,m-1] : [1,m-7];
  const dayCell = d => d <= 28 ? [2 + Math.floor((d-1)/7), (d-1)%7] : [6,d-29];

  function verify(month, day, cert) {
    if (!(month >= 1 && month <= 12 && day >= 1 && day <= 31)) return false;
    if (!Array.isArray(cert) || cert.length !== 8) return false;
    const ids = cert.map(x => x.piece);
    if (new Set(ids).size !== 8 || !"ABCDEFGH".split("").every(x => ids.includes(x))) return false;
    const covered = [];
    for (const pl of cert) {
      const shape = variants[pl.piece]?.[pl.orientation];
      if (!shape) return false;
      for (const [dr,dc] of shape) covered.push([pl.row+dr, pl.col+dc]);
    }
    if (covered.length !== 41) return false;
    const keys = covered.map(([r,c]) => `${r},${c}`);
    if (new Set(keys).size !== keys.length) return false;
    if (!keys.every(k => board.has(k))) return false;
    const [mr,mc] = monthCell(month), [dr,dc] = dayCell(day);
    if (keys.includes(`${mr},${mc}`) || keys.includes(`${dr},${dc}`)) return false;
    return true;
  }
  window.CalendarOCamlVerifier = { verify, engine: "js-fallback" };
